#!/usr/bin/env python3
"""Collect every CJK character the panel's own string literals use.

The font atlas is built from this explicit set instead of the whole CJK block: the
panel draws a few hundred distinct characters, and a 20k-glyph atlas costs tens of
megabytes of texture plus a visible hitch while it is rasterised. The trade-off is
that a newly added label with a character that is not in the set would render as a
missing glyph, so re-run this after editing labels:

    python scripts/collect_glyphs.py

It rewrites src/neurodragon/ui/Glyphs.h in place.
"""

from __future__ import annotations

import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
UI_DIR = REPO / "src" / "neurodragon" / "ui"
LANG_DIR = REPO / "src" / "lang"
OUTPUT = UI_DIR / "Glyphs.h"

HEADER = """#pragma once

// GENERATED by scripts/collect_glyphs.py - do not edit by hand.
//
// Every non-ASCII character the panel can draw: CJK ideographs *and* the
// full-width punctuation (，。（）：？！、…) that Chinese text uses. The panel's
// text lives in src/lang/*.json (ll::i18n), so the catalogue is the primary
// source; the ui sources are scanned too for untranslated strings.
inline constexpr char kUiGlyphs[] = "{glyphs}";
"""


def collect() -> str:
    """All non-ASCII characters used by the panel, deduplicated and sorted.

    Restricting this to the CJK block was the reason full-width punctuation
    rendered as '?' in game: ， is U+FF0C and （ is U+FF08, neither is inside
    4E00-9FFF, so they never made it into the font atlas.
    """
    characters: set[str] = set()
    for path in sorted(LANG_DIR.glob("*.json")):
        for character in path.read_text(encoding="utf-8"):
            if ord(character) > 0x7F:
                characters.add(character)
    for path in sorted(UI_DIR.glob("*.cpp")):
        for character in path.read_text(encoding="utf-8"):
            if ord(character) > 0x7F:
                characters.add(character)
    return "".join(sorted(characters))


def main() -> int:
    glyphs = collect()
    if not glyphs:
        print("no CJK characters found; refusing to write an empty set", file=sys.stderr)
        return 1
    OUTPUT.write_text(HEADER.format(glyphs=glyphs), encoding="utf-8", newline="\n")
    print(f"{len(glyphs)} unique non-ASCII glyphs -> {OUTPUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
